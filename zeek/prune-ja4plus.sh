#!/bin/sh
# Remove JA4+ (FoxIO License 1.1) from the installed ja4-zeek-scripts package, leaving
# JA4 (BSD-3-Clause) working.
#
# RUNS AT IMAGE BUILD TIME. See zeek/Containerfile for the licensing reasoning; this file
# is the mechanism, kept separate so it can be run and asserted against a plain directory
# instead of only inside a container build.
#
# USAGE:  prune-ja4plus.sh <package-dir>
#
# WHY DELETE RATHER THAN DISABLE. The package gates its submodules with
# `@if (JA4S_enabled) @load ./ja4s @endif`, and `@if` is evaluated WHEN THE FILE IS
# LOADED. Disabling the options after loading is therefore silently ignored -- measured on
# a live sensor: 28 of 28 ssl records carried a populated ja4s while the config claimed it
# was off. That was fixed by reordering the loads, but it shows the class of failure: the
# licensed code was IN the image, and only the correctness of a load order stood between it
# and being shipped. Deleting the files removes the question -- nothing to mis-order,
# nothing a package update can re-enable by changing a default.
#
# The BSD module depends only on `./config`, `../utils/*` and its own directory (verified by
# grepping every @load in the package), so none of the deleted directories is a dependency
# of what remains.
set -eu

DIR=${1:?usage: prune-ja4plus.sh <package-dir>}
[ -d "$DIR" ] || { echo "ERROR: no such package directory: $DIR" >&2; exit 1; }

# The FoxIO submodules. Kept as the authoritative list so the assertions cannot drift from
# the deletions.
FOXIO_MODULES="ja4s ja4h ja4ssh ja4x ja4l ja4t ja4d"

# The FoxIO option names, used both to filter config.zeek and to assert none survives.
# NOTE: `ja4` and `JA4_raw` are BSD and must be KEPT -- an assertion that matched the bare
# string "JA4_enabled" would fail on the option we are required to keep.
FOXIO_OPTIONS="JA4S_enabled JA4S_raw JA4H_enabled JA4H_raw JA4L_enabled JA4SSH_enabled JA4T_enabled JA4TS_enabled JA4X_enabled JA4D_enabled"

echo "pruning JA4+ from $DIR"

# 1. Delete the submodule directories.
for m in $FOXIO_MODULES; do
    rm -rf "$DIR/$m"
done

# 2. Delete the package's own tests. They carry recorded OUTPUT of the licensed code --
#    e.g. tests/Traces/Scripts.ja4-ssh2/ja4ssh.log -- so leaving them would ship JA4+
#    fingerprints inside the image even with the code that produced them gone.
rm -rf "$DIR/tests"

# 3. Replace the loader with one that has no way to reference a FoxIO module. The upstream
#    file's `@if (JA4S_enabled) @load ./ja4s @endif` blocks would now reference deleted
#    directories, and rewriting it removes the option names from the file entirely.
cat > "$DIR/__load__.zeek" <<'ZEEK'
# Weirvern: JA4 (BSD-3-Clause) ONLY. The JA4+ submodules are removed from this image at
# build time -- see zeek/Containerfile and prune-ja4plus.sh.
#
# There are deliberately no JA4S/H/X/SSH/T/L/D loads here, and the options that would gate
# them no longer exist in config.zeek, so this file cannot be made to load licensed code by
# reordering, or by a package update changing which way a default points.
module FINGERPRINT;

export { type Info: record {}; }
redef record connection += { fp: FINGERPRINT::Info &optional; };

@load ./config
@load ./ja4
ZEEK

# 4. Filter config.zeek. Generated by REMOVAL rather than written out fresh, so an option
#    upstream adds that the BSD module needs is preserved automatically -- a hand-written
#    replacement would silently drop it on the next package update.
tmp="$DIR/config.zeek.filtered"
: > "$tmp"
for opt in $FOXIO_OPTIONS; do
    # Mark the lines to drop, so the filter is an exact `option <name>` match rather than a
    # substring one. `JA4T_enabled` is a substring of `JA4TS_enabled`, so substring
    # matching would remove the wrong lines.
    # Mark the line numbers of the options to remove. An EXACT `option <name>:` match, not
    # a substring one -- `JA4T_enabled` is a substring of `JA4TS_enabled`, so a naive
    # substring filter would remove the wrong lines.
    grep -nE "^[[:space:]]*option[[:space:]]+$opt[[:space:]]*:" "$DIR/config.zeek" 2>/dev/null \
        | cut -d: -f1 >> "$tmp.lines" || true
done

# Delete the marked lines, plus the now-dangling "# FoxIO license required for JA4+" label,
# plus the runs of blank lines the deletions leave behind. An awk pass rather than several
# greps: the file's shape has to survive, and the alternative needed a Python fallback that
# this image may not have.
sort -un "$tmp.lines" 2>/dev/null > "$tmp.sorted" || : > "$tmp.sorted"
awk -v list="$tmp.sorted" '
    BEGIN { while ((getline n < list) > 0) if (n != "") drop[n] = 1 }
    /FoxIO license required/ { next }
    FNR in drop { next }
    # Collapse consecutive blanks left by removed options, but keep one so sections stay
    # visually separated.
    /^[[:space:]]*$/ { if (blank) next; blank = 1; print; next }
    { blank = 0; print }
' "$DIR/config.zeek" > "$tmp"

{
    echo "# Weirvern: the FoxIO-licensed JA4+ options (JA4S/H/X/SSH/T/L/D and their _raw"
    echo "# variants) were REMOVED at build time, not disabled. See zeek/Containerfile and"
    echo "# prune-ja4plus.sh. What follows is JA4 only, which is BSD-3-Clause."
    cat "$tmp"
} > "$DIR/config.zeek.new"
mv "$DIR/config.zeek.new" "$DIR/config.zeek"
rm -f "$tmp" "$tmp.lines" "$tmp.sorted"

# 5. ASSERTIONS. These fail the build rather than printing a warning: the failure mode is
#    shipping licensed code in a distributed image, which is invisible at runtime and
#    expensive afterwards. A licensing guarantee that depends on a human reading a comment
#    is not a guarantee.
fail=0

for m in $FOXIO_MODULES; do
    if [ -e "$DIR/$m" ]; then
        echo "ASSERT FAIL: submodule directory still present: $DIR/$m" >&2
        fail=1
    fi
done

if [ -e "$DIR/tests" ]; then
    echo "ASSERT FAIL: the package's tests directory still present (holds recorded JA4+ output)" >&2
    fail=1
fi

for opt in $FOXIO_OPTIONS; do
    if grep -rqE "\b$opt\b" "$DIR" 2>/dev/null; then
        echo "ASSERT FAIL: a FoxIO option is still referenced: $opt" >&2
        fail=1
    fi
done

# The BSD option must SURVIVE. An over-eager filter that removed these would leave a
# sensor that parses and produces no fingerprint at all -- silently useless, which is worse
# than a loud build failure.
for opt in JA4_enabled JA4_raw delimiter; do
    if ! grep -rqE "\b$opt\b" "$DIR/config.zeek"; then
        echo "ASSERT FAIL: the BSD option '$opt' was removed; JA4 could not work" >&2
        fail=1
    fi
done

if [ "$fail" -ne 0 ]; then
    echo "JA4+ removal did not complete; refusing to build an image that may carry licensed code" >&2
    exit 1
fi

echo "JA4+ removed: no submodule, no test data, no FoxIO option, and JA4 retained"
